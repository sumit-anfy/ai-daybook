"""OKF node validator — the first deterministic slice of the Librarian.

Enforces the contract defined in schemas/node.schema.md (§3 SPEC, §6 RULES) over a
snapshot of the corpus. The *type* vocabulary is read live from
schemas/type-registry.md so that node is the single source of truth for it; the
status/maturity/canonical rules mirror node.schema and are noted as such.

Scope (v1): static, single-snapshot structural validation + cross-node link
integrity. It does NOT check status/maturity *transitions* — those need a
before-state and land with the write tools (create/update_node).

Usage:
    python -m librarian.validate [CORPUS_ROOT]

Exit code 0 if no ERRORs (warnings allowed), 1 otherwise. Suitable for a
pre-commit hook.
"""
from __future__ import annotations

import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path

import yaml

try:  # works both as `python librarian/validate.py` and `python -m librarian.validate`
    from ids import ID_PATTERN
    from yamlio import safe_load as _yload
    import summary as _summary
except ImportError:
    from librarian.ids import ID_PATTERN
    from librarian.yamlio import safe_load as _yload
    from librarian import summary as _summary

# ── Vocabulary that mirrors node.schema §3 (rarely changes; kept in code) ──────
STATUSES = {"active", "parked", "superseded", "retired"}
MATURITIES = {"captured", "candidate", "established"}
# `coda_table` / `coda_row` were REMOVED 2026-08-03 with the task substrate move
# (the tasks-live-in-the-task-app decision supersedes the first task-substrate decision). The owner ruled that Coda "is not the
# fallback and not the archive — it is simply no longer the task system", so the
# enum enforces that rather than merely documenting it: a Coda task pointer can no
# longer be minted. Verified safe first — NO node carries a coda_ resource block;
# The first task-substrate decision mentions the kinds in prose only, and prose is not validated.
RESOURCE_KINDS = {"todoist_project", "todoist_task", "supabase_table", "calendar",
                  "api", "file", "gdrive_file", "gdrive_folder"}
REQUIRED_FIELDS = ["id", "type", "title", "status", "maturity", "canonical",
                   "created_at", "updated_at", "project"]
# Every field node.schema §3 SPEC declares. Resource nodes may carry NOTHING
# else at top level (a pointer with extra fields is smuggled state); other
# types may extend (playbooks carry skill_type/triggers/output_contract).
KNOWN_FIELDS = {"id", "type", "title", "summary", "status", "maturity", "canonical",
                "created_at", "updated_at", "project", "tags", "source",
                "confidence", "relates_to", "supersedes", "superseded_by", "resource",
                # ASKS (v1.9, 2026-09-29): the everyday
                # phrasings a stranger would type when this node is the answer.
                # Retrieval metadata, generated by a model from the body, indexed and
                # embedded like the summary, never shown as knowledge. Measured before
                # adoption on 532 nodes: stranger-question findability 9-11 of 20 →
                # 14-16 of 20, benchmark 51/61/66 → 56/66/67, no regression
                # (the retrieval-measurement record and the 2026-09-29 session).
                "asks",
                # WORK-STATE, promoted out of prose 2026-08-04. `log` nodes
                # carried their lifecycle in ENGLISH — "OPEN WORK" in the title,
                # "SHIPPED"/"CLOSED" in the summary — which a validator cannot read,
                # so a node stayed titled OPEN WORK after shipping and passed green.
                # Measured before building: 23 live titles carry a state word, and a
                # text-only contradiction check (no new field) flagged 5 of which only
                # 1 was real — "the four-test GAP", "COMMITTED OPEN WORK" and an
                # UNRULED node matching twice. 80% false positives is the check that
                # trains you to ignore it (the fail-loudly rule §3). A field cannot be ambiguous; the
                # word "gap" always will be.
                "work_state",
                # PARTIAL SUPERSESSION — a DATE, not a link, and the shape changed on
                # evidence. It was proposed (the false-title handover §3) as a link mirroring
                # `superseded_by`, but of the 29 live nodes signalling partial
                # supersession in prose, only 6 name another node — for the other 23
                # the correction is INLINE in the node's own body, so there is nothing
                # to point at. A link would have fitted a fifth of the subjects.
                # Presence means: part of this node no longer holds; read its dated
                # correction block. Where another node carries the replacement, that
                # is already a `relates_to` edge and is named in the correction.
                "superseded_in_part",
                # grandfathers a session written before the completeness check; the
                # write path skips it, the audit path still reports it (the completeness-check spec §7)
                "unfiled_rulings_legacy",
                # opts a node out of the in-body reference scan. For the three
                # legitimate cases only: schema docs that print an id as an EXAMPLE,
                # audit nodes that QUOTE a broken id in order to report it, and nodes
                # citing a node that was deliberately deleted (a deleted node, another deleted node).
                "allow_dangling_refs"}

# Directories that are not part of the node corpus.
SKIP_DIRS = {".git", "librarian", "tests", "deploy", "__pycache__", "indexes",
             ".venv", "venv", ".pytest_cache"}

SEVERITY_ERROR = "ERROR"
SEVERITY_WARN = "WARN"

# Below this a summary is too thin to carry retrieval signal (§15 of the
# completeness spec). Tuned to flag stubs, not to police prose length: the spec said
# ~15, but the only node 15 caught was node.schema's own 14-word summary, which is
# accurate and dense. Padding a good summary to clear a threshold is the "false
# impression of coverage" §15 warns about, so the threshold moved instead.
SUMMARY_MIN_WORDS = 12

# The lifecycle of a piece of work, as a VALUE rather than a sentence in a title.
# `open` — committed and not done; `shipped` — built, may still have a tail;
# `closed` — nothing further will happen here.
WORK_STATES = {"open", "shipped", "closed"}


@dataclass
class Finding:
    severity: str
    path: str
    message: str

    def __str__(self) -> str:
        return f"  [{self.severity}] {self.path}: {self.message}"


@dataclass
class Node:
    id: str
    path: Path
    fm: dict
    # The prose under the frontmatter. Carried because load_corpus has already
    # read the whole file to parse the frontmatter and was discarding the rest —
    # so retrieval can index bodies (librarian/context.py) without a second pass
    # over the corpus. 1.92 MB across 309 nodes as at 2026-08-04, which is cheaper
    # to hold than to re-read. Synthetic Nodes built inside store.py for
    # validation leave it empty; nothing reads it on those paths.
    body: str = ""


# ── Frontmatter + registry loading ────────────────────────────────────────────
_FM_RE = re.compile(r"^---\s*\n(.*?)\n---\s*(?:\n|$)", re.DOTALL)


def parse_document(text: str):
    """Return (frontmatter_dict, ok, body). One pass over the file text.

    Split out from parse_frontmatter so load_corpus can keep the body it was
    already reading and throwing away."""
    m = _FM_RE.match(text)
    if not m:
        return None, False, ""
    data = _yload(m.group(1))
    if not isinstance(data, dict):
        return None, False, ""
    return data, True, text[m.end():]


def parse_frontmatter(text: str):
    """Return (frontmatter_dict, ok). ok is False when no frontmatter block."""
    fm, ok, _ = parse_document(text)
    return fm, ok


def _first_yaml_block_with_key(body: str, key: str):
    """Extract the first ```yaml fenced block whose parsed top-level has `key`."""
    for block in re.findall(r"```yaml\s*\n(.*?)```", body, re.DOTALL):
        try:
            parsed = _yload(block)
        except yaml.YAMLError:
            continue
        if isinstance(parsed, dict) and key in parsed:
            return parsed[key]
    return None


class CorpusRootError(RuntimeError):
    """OKF_ROOT does not point at a corpus."""


def assert_corpus_root(root: Path) -> Path:
    """Refuse to start when OKF_ROOT is not a corpus — call this before serving.

    Since the code/corpus split, OKF_ROOT is the ONLY thing connecting the server
    to its data, and its old default was the code directory. An unset or wrong
    value would otherwise start a healthy-looking server over zero nodes, which
    reads as "the corpus is empty" rather than "you pointed me at the wrong
    place" — the silent-pass failure of the fail-loudly rule.

    The probe is `schemas/type-registry.md` rather than a node count, because the
    registry is what `load_registry_types` reads live: without it the vocabulary
    is empty and every node fails anyway. A corpus with no nodes yet is legal;
    a corpus with no registry is not.
    """
    if not (root / "schemas" / "type-registry.md").exists():
        raise CorpusRootError(
            f"OKF_ROOT={root} is not an OKF corpus — schemas/type-registry.md is "
            "missing. Point OKF_ROOT at a corpus (examples/corpus is one); the "
            "code directory itself is not a corpus root.")
    return root


def load_registry_types(root: Path) -> set[str]:
    """Read the active node-type vocabulary live from the type-registry node.

    Deferred types are intentionally excluded — a node using one must fail until
    the type is promoted (grow-on-friction, registry §1). An empty result means
    the registry is missing/unparseable: callers must treat that as a BROKEN
    corpus (fail closed), never as "no type checking".
    """
    reg_path = root / "schemas" / "type-registry.md"
    if not reg_path.exists():
        return set()
    registry = _first_yaml_block_with_key(reg_path.read_text(encoding="utf-8"), "REGISTRY")
    if not isinstance(registry, dict) or not isinstance(registry.get("node_types"), dict):
        return set()   # structurally broken block == missing (fail closed downstream)
    return set(registry["node_types"].keys())


def load_folder_map(root: Path) -> dict:
    """type -> default folder, live from the registry's FOLDER_MAP block."""
    reg_path = root / "schemas" / "type-registry.md"
    if not reg_path.exists():
        return {}
    fmap = _first_yaml_block_with_key(reg_path.read_text(encoding="utf-8"), "FOLDER_MAP")
    if not isinstance(fmap, dict):
        return {}
    return {k: str(v).lstrip("/") for k, v in fmap.items()}


def load_registry_projects(root: Path) -> set[str]:
    """Read the project/world vocabulary live from the type-registry node's §4
    PROJECT_REGISTRY block, so that node is the single source of truth for it —
    exactly as load_registry_types does for the type axis. An empty result means
    the block is missing/unparseable: callers must treat that as a BROKEN corpus
    (fail closed), never as "no project checking".
    """
    reg_path = root / "schemas" / "type-registry.md"
    if not reg_path.exists():
        return set()
    reg = _first_yaml_block_with_key(reg_path.read_text(encoding="utf-8"), "PROJECT_REGISTRY")
    if not isinstance(reg, dict) or not isinstance(reg.get("projects"), dict):
        return set()   # structurally broken block == missing (fail closed downstream)
    return set(reg["projects"].keys())


# ── Validation ────────────────────────────────────────────────────────────────
def iter_node_files(root: Path):
    for path in sorted(root.rglob("*.md")):
        if any(part in SKIP_DIRS for part in path.relative_to(root).parts):
            continue
        yield path


def _dateish(v) -> bool:
    import datetime
    if isinstance(v, (datetime.date, datetime.datetime)):
        return True
    if isinstance(v, str):  # full parse — '2026-99-99junk' is not a date
        try:
            datetime.date.fromisoformat(v)
            return True
        except ValueError:
            return False
    return False


def check_node(node: Node, valid_types: set[str], out: list[Finding],
               folder_map: dict | None = None,
               valid_projects: set[str] | None = None) -> None:
    fm, rel = node.fm, str(node.path)

    def err(msg):
        out.append(Finding(SEVERITY_ERROR, rel, msg))

    def warn(msg):
        out.append(Finding(SEVERITY_WARN, rel, msg))

    # Required fields present (node.schema §3 required_in_valid_node)
    for field in REQUIRED_FIELDS:
        if fm.get(field) is None:
            err(f"missing required field '{field}'")

    if fm.get("id") and not ID_PATTERN.match(str(fm["id"])):
        err(f"malformed id '{fm['id']}'")

    # Defense-in-depth: frontmatter id must equal the node's identity. Guards
    # against any write path building a candidate whose id was mutated (P0).
    if fm.get("id") and str(fm["id"]) != node.id:
        err(f"frontmatter id '{fm['id']}' does not match node identity '{node.id}'")

    # Enum fields must be strings BEFORE membership tests — `type: []` is a
    # finding, never an unhashable-type crash that kills the whole run.
    node_type = fm.get("type")
    if node_type is not None and not isinstance(node_type, str):
        err(f"type must be a string, got {type(node_type).__name__}")
        node_type = None
    if node_type and valid_types and node_type not in valid_types:
        err(f"type '{node_type}' not in registry vocabulary {sorted(valid_types)}")

    # project (the world axis) validated against PROJECT_REGISTRY, same as type.
    # Guard isinstance(str) so a non-string project is a "must be a string"
    # finding (below), never an unhashable-membership crash. project is REQUIRED
    # (node.schema v1.7, 2026-09-06): an absent one is already a "missing required
    # field" finding from the REQUIRED_FIELDS loop above — seven nodes filed
    # 2026-08-10→15 arrived with no home because the write path let them.
    project = fm.get("project")
    if isinstance(project, str) and valid_projects and project not in valid_projects:
        err(f"project '{project}' not in registry vocabulary {sorted(valid_projects)}")

    status = fm.get("status")
    if status is not None and not isinstance(status, str):
        err(f"status must be a string, got {type(status).__name__}")
        status = None
    if status is not None and status not in STATUSES:
        err(f"status '{status}' not in {sorted(STATUSES)}")

    maturity = fm.get("maturity")
    if maturity is not None and not isinstance(maturity, str):
        err(f"maturity must be a string, got {type(maturity).__name__}")
        maturity = None
    if maturity is not None and maturity not in MATURITIES:
        err(f"maturity '{maturity}' not in {sorted(MATURITIES)}")

    canonical = fm.get("canonical")
    if canonical is not None and not isinstance(canonical, bool):
        err(f"canonical must be a boolean, got {canonical!r}")

    # RULE: canonical=true permitted only when status=active AND maturity=established
    if canonical is True and not (status == "active" and maturity == "established"):
        err(f"canonical=true requires status=active+maturity=established "
            f"(got status={status}, maturity={maturity})")

    # RULE: resource nodes require a resource pointer (never a copy) and carry
    # identity ONLY — any extra key (due_date, status…) is live state sneaking in
    if node_type == "resource":
        res = fm.get("resource")
        if not isinstance(res, dict):
            err("resource node missing 'resource' block")
        else:
            kind = res.get("kind")
            if not isinstance(kind, str) or kind not in RESOURCE_KINDS:
                err(f"resource.kind {kind!r} not in {sorted(RESOURCE_KINDS)}")
            if not isinstance(res.get("uri"), str) or not res["uri"]:
                err(f"resource.uri must be a non-empty string, got {res.get('uri')!r}")
            extra = set(res) - {"kind", "uri"}
            if extra:
                err(f"resource block carries state ({sorted(extra)}) — identity only: kind, uri")
    # RULE: frontmatter is a CLOSED vocabulary for EVERY type, not just `resource`.
    # `store.update_node` writes whatever keys it is handed straight into the node, so
    # a malformed `changes` dict is serialised verbatim and validates green. Observed
    # 2026-07-28: a reference node (a living reference node) carried `frontmatter:` and `body_patch:`
    # — an update-INSTRUCTION object passed as the changes payload. The instruction was
    # never executed, the summary update inside it never landed, and nothing flagged it
    # for six days. An unknown key is never intentional: it is a typo or a misrouted
    # payload. ERROR, so the write path refuses it at the moment it is made.
    top_extra = set(fm) - KNOWN_FIELDS
    if top_extra:
        if node_type == "resource":
            # identity-only applies to the WHOLE node: a pointer with extra
            # top-level fields (due_date, task_status…) is smuggled state too
            err(f"resource node carries unknown top-level fields {sorted(top_extra)} "
                "— pointers hold identity, never state")
        else:
            err(f"unknown frontmatter field(s) {sorted(top_extra)} — frontmatter is a "
                f"closed vocabulary; known fields are {sorted(KNOWN_FIELDS)}")

    # COMPLETENESS, not validity: a node with no (or a stub) summary is structurally
    # under-retrievable — `brief` returns the summary as the headline and it carries
    # real retrieval weight, so an empty one is valid but effectively invisible
    # (the completeness-check spec §15). A warning, never an error: existing nodes
    # must not become unwritable.
    summary = fm.get("summary")
    if isinstance(summary, str) or summary is None:
        words = len((summary or "").split())
        if words == 0:
            warn("summary is empty or missing — the node is structurally under-retrievable")
        elif words < SUMMARY_MIN_WORDS:
            warn(f"summary is only {words} words (<{SUMMARY_MIN_WORDS}) — likely too thin to retrieve on")
        # a bullet summary's shape (librarian/summary.py); legacy prose is never checked
        for w in _summary.check(summary, node.body, fm.get("type")):
            warn(w)

    # scalar shape checks
    for str_field in ("title", "summary", "project", "source"):
        if fm.get(str_field) is not None and not isinstance(fm[str_field], str):
            err(f"{str_field} must be a string, got {type(fm[str_field]).__name__}")
    if fm.get("confidence") is not None and not isinstance(fm["confidence"], (int, float)):
        err(f"confidence must be numeric, got {fm['confidence']!r}")

    # superseded_by is Librarian-owned and only meaningful on superseded nodes
    if fm.get("superseded_by") is not None and status != "superseded":
        err(f"superseded_by present on a node with status={status!r} — only "
            "superseded nodes carry it (Librarian-owned field)")
    for date_field in ("created_at", "updated_at"):
        if fm.get(date_field) is not None and not _dateish(fm[date_field]):
            err(f"{date_field} must be a date (YYYY-MM-DD), got {fm[date_field]!r}")

    # ── work-state and partial supersession, promoted out of prose 2026-08-04 ──
    ws = fm.get("work_state")
    if ws is not None:
        if ws not in WORK_STATES:
            err(f"work_state must be one of {sorted(WORK_STATES)}, got {ws!r}")
        # Scoped to `log` ON PURPOSE. Sessions and notes use "gap", "open" and
        # "shipped" as ORDINARY VOCABULARY — every false positive in the pre-build
        # measurement came from that ("the four-test gap", "COMMITTED OPEN WORK").
        # A log is the only type whose whole reason for existing is a piece of work
        # with a lifecycle, so it is the only type where the field means one thing.
        elif node_type != "log":
            err(f"work_state is only meaningful on `log` nodes (this is a {node_type!r}) "
                "— other types use those words as ordinary vocabulary, which is exactly "
                "why the state needed a field rather than a text scan")

    sip = fm.get("superseded_in_part")
    if sip is not None:
        if not _dateish(sip):
            err("superseded_in_part must be the DATE (YYYY-MM-DD) the node was partly "
                f"corrected, got {sip!r} — it is not a link; where another node carries "
                "the replacement, that is a relates_to edge named in the correction block")
        elif status == "superseded":
            # whole supersession subsumes partial; carrying both says the node is
            # simultaneously wholly and partly replaced, which is not a state.
            err("superseded_in_part on a node with status=superseded — whole "
                "supersession already covers it; drop the partial marker")
        elif _dateish(fm.get("created_at")) and str(sip) < str(fm["created_at"]):
            err(f"superseded_in_part ({sip}) predates created_at ({fm['created_at']}) "
                "— a node cannot be corrected before it existed")
    asks = fm.get("asks")
    if asks is not None:
        if not isinstance(asks, list) or not all(isinstance(a, str) and a.strip() for a in asks):
            err("asks must be a list of non-empty strings — the everyday phrasings a "
                "stranger would type when this node is the answer")
        elif len(asks) > 8 or any(len(a) > 160 for a in asks):
            err("asks holds at most 8 phrasings of at most 160 characters — retrieval "
                "metadata, not a second summary")

    for list_field in ("tags", "relates_to"):
        if list_field in fm and not isinstance(fm[list_field], list):
            err(f"'{list_field}' must be a list")

    # filing check: node should live in its type's folder (schemas/ is the
    # documented exception for reference nodes — the registry says so)
    if folder_map and node_type in folder_map:
        actual = node.path.parts[0] if len(node.path.parts) > 1 else ""
        expected = folder_map[node_type]
        if actual != expected and not (actual == "schemas" and node_type == "reference"):
            warn(f"type '{node_type}' files under /{expected}, found in /{actual}")


def check_cross_node(nodes: list[Node], by_id: dict, out: list[Finding]) -> None:
    for node in nodes:
        fm, rel = node.fm, str(node.path)

        def err(msg):
            out.append(Finding(SEVERITY_ERROR, rel, msg))

        # relates_to must resolve to existing nodes (no dangling soft links);
        # non-string entries are findings, never unhashable-lookup crashes
        relates = fm.get("relates_to")
        for target in (relates if isinstance(relates, list) else []):
            if not isinstance(target, str):
                err(f"relates_to entry must be an id string, got {type(target).__name__}")
            elif target not in by_id:
                err(f"relates_to points to unknown id '{target}'")

        # supersedes invariant (node.schema §6): the superseded target must be
        # marked superseded, non-canonical, and back-point here. A RETIRED
        # carrier is exempt — its supersedes pointer is historical, which is
        # what makes the schema's "or successor retired" un-supersession
        # route actually usable.
        sup = fm.get("supersedes")
        if sup is not None and not isinstance(sup, str):
            err(f"supersedes must be an id string, got {type(sup).__name__}")
            sup = None
        if sup and fm.get("status") != "retired":
            target = by_id.get(sup)
            if target is None:
                err(f"supersedes points to unknown id '{sup}'")
            else:
                t = target.fm
                if t.get("status") != "superseded":
                    err(f"supersedes target '{sup}' must have status=superseded "
                        f"(got {t.get('status')})")
                if t.get("canonical") is True:
                    err(f"supersedes target '{sup}' must have canonical=false")
                if t.get("superseded_by") != fm.get("id"):
                    err(f"supersedes target '{sup}' must set superseded_by={fm.get('id')}")

        # …and the invariant in reverse: every superseded node needs a real,
        # reciprocal successor. Catches hand-edited status flips.
        if fm.get("status") == "superseded":
            sb = fm.get("superseded_by")
            if not sb or not isinstance(sb, str):
                err("status=superseded but no superseded_by — supersession requires a successor")
            elif sb not in by_id:
                err(f"superseded_by points to unknown id '{sb}'")
            elif by_id[sb].fm.get("supersedes") != fm.get("id"):
                err(f"successor '{sb}' does not point back via supersedes")

    # RULE (node.schema §6): flag — never auto-resolve — competing canonical
    # claims: two active+canonical nodes with the same normalized title.
    canon: dict = {}
    for node in nodes:
        fm = node.fm
        if fm.get("canonical") is True and fm.get("status") == "active" \
                and isinstance(fm.get("title"), str):
            key = re.sub(r"[^a-z0-9]+", " ", fm["title"].lower()).strip()
            canon.setdefault(key, []).append(node)
    for key, group in canon.items():
        if len(group) > 1:
            paths = ", ".join(str(n.path) for n in group)
            for n in group:
                out.append(Finding(SEVERITY_WARN, str(n.path),
                                   f"duplicate canonical claim for '{key}' ({paths})"))


def load_corpus(root: Path):
    """Read all node files off disk. Returns (nodes, by_id, skipped, valid_types,
    file_findings). Pure I/O + parse; no rule checks (see run_checks). A file that
    cannot be parsed, or that has frontmatter without an id, is an ERROR finding —
    never a silent skip (only frontmatter-less files like READMEs skip)."""
    valid_types = load_registry_types(root)
    nodes: list[Node] = []
    by_id: dict = {}
    skipped: list[str] = []
    file_findings: list[Finding] = []

    for path in iter_node_files(root):
        rel = str(path.relative_to(root))
        try:
            fm, ok, body = parse_document(path.read_text(encoding="utf-8"))
        except yaml.YAMLError as e:
            file_findings.append(Finding(SEVERITY_ERROR, rel,
                                         f"malformed YAML frontmatter: {str(e).splitlines()[0]}"))
            continue
        if not ok:
            skipped.append(rel)
            continue
        if "id" not in fm:
            file_findings.append(Finding(SEVERITY_ERROR, rel,
                                         "frontmatter present but missing 'id'"))
            continue
        node = Node(id=str(fm["id"]), path=path.relative_to(root), fm=fm, body=body)
        if node.id in by_id:
            file_findings.append(Finding(SEVERITY_ERROR, str(node.path),
                                         f"duplicate id '{node.id}' "
                                         f"(also {by_id[node.id].path})"))
        else:
            by_id[node.id] = node
        nodes.append(node)

    return nodes, by_id, skipped, valid_types, file_findings


def run_checks(nodes: list[Node], by_id: dict, valid_types: set[str],
               folder_map: dict | None = None,
               valid_projects: set[str] | None = None) -> list[Finding]:
    """Apply all node + cross-node rules to an in-memory set. Used both by the CLI
    and by the store to validate a candidate node before writing it."""
    findings: list[Finding] = []
    for node in nodes:
        check_node(node, valid_types, findings, folder_map, valid_projects)
    check_cross_node(nodes, by_id, findings)
    return findings


# A full node id written in prose. `relates_to` is validated for dangling targets;
# an id in the BODY never was — which is how a truncated placeholder survived inside a
# ratified playbook, and how one node came to cite an id spliced from two real ones.
_BODY_ID_RE = re.compile(r"okf_\d{8}_\d{6}_[0-9a-f]{4}")
# A REAL 8-digit date prefix not followed by a well-formed `HHMMSS_hhhh` is a broken
# reference, never a template: `okf_20260728_...` (truncated) and `okf_20260728_?the gated-deletion decision
# (malformed) both qualify. Generic forms — `okf_...`, `okf_<YYYYMMDD>_<HHMMSS>_<4char>`
# — have no digits in the date position and are deliberately NOT matched; the schema and
# the playbooks legitimately print those.
#
# Widened 2026-07-29 from `okf_\d{8}_\.\.\.` after writing `okf_20260728_?the gated-deletion decision by hand:
# the ellipsis-only form missed it, and `relates_to` validation could not see it either
# because it was in the body. Measured before widening — the corpus contains exactly 3
# non-valid `okf_` tokens and 2 are legitimate templates, so this adds no false positives.
_TRUNCATED_ID_RE = re.compile(r"okf_\d{8}_(?!\d{6}_[0-9a-f]{4}\b)[^\s`)\]]*")


def scan_body_refs(root: Path, nodes: list[Node], by_id: dict) -> list[Finding]:
    """Node ids written in prose that resolve to nothing.

    WARNING, never an error: a reference to a node that was deliberately deleted is
    legitimate history, and the corpus cannot tell that apart from a typo. Nodes with
    `allow_dangling_refs: true` are skipped whole.
    """
    findings: list[Finding] = []
    for node in nodes:
        if node.fm.get("allow_dangling_refs") is True:
            continue
        try:
            text = (root / node.path).read_text(encoding="utf-8")
        except OSError:
            continue
        parts = text.split("---", 2)
        body = parts[2] if len(parts) > 2 else text
        for lineno, line in enumerate(body.splitlines(), start=1):
            for ref in _BODY_ID_RE.findall(line):
                if ref not in by_id and ref != node.id:
                    findings.append(Finding(
                        SEVERITY_WARN, str(node.path),
                        f"in-body reference to a node that does not exist: {ref} "
                        f"(line {lineno})"))
            for _ in _TRUNCATED_ID_RE.findall(line):
                findings.append(Finding(
                    SEVERITY_WARN, str(node.path),
                    f"truncated node id in body (line {lineno}) — a real date prefix "
                    "followed by '...' is an unfinished reference, not a template"))
    return findings


# The node carrying the ratified scope, and what counts toward it. Optional:
# unset (the default) turns the check off.
_RATIFIED_SCOPE_NODE = os.environ.get("OKF_RATIFIED_SCOPE_NODE", "")
# `[A-Z]+\d*` not `[A-Z]`: the library is A–Q today, but "Case AA" or "Case Z0" would
# slip past a single-letter pattern and the check would report "fine" while the library
# grew — an undercounting guard is worse than none. Measured: all three candidate
# patterns match exactly 17 on the real corpus, so the looser one costs no precision.
# Case letters were RETIRED on 2026-09-03 (the owner's ruling, first applied in
# A case note): new cases are titled "Case — <name>". For four days the
# pattern above counted only the lettered form, so the validator said 20 while the
# library held 25 — the undercount this comment warned about, arriving from a title
# convention rather than a letter shape. Both forms count. Found 2026-09-08 when the
# re-ratification was about to be written against the counter's figure.
_CASE_TITLE_RE = re.compile(r"^Case\s+(?:[A-Z]+\d*\b|[—–-]\s)", re.I)


def scan_ratified_scope(root: Path, nodes: list[Node], by_id: dict) -> list[Finding]:
    """Warn when the precedent library outgrows the count its risk acceptance was ratified at.

    A risk acceptance is argued against a scope. The ratified-scope node's controls — a secure surface,
    redaction deferred to the automation boundary — were each argued for a library of 5–7
    cases. The library grew to 15 without anyone re-arguing them, and to 17 within two days
    of being re-ratified at 15. The revisit trigger never fired because it was a condition
    nobody was watching.

    WARN, never ERROR: filing a new case is legitimate work and must not be refused. What
    needs a human is the risk acceptance, not the write — detection is not declaration
    (the five-layer audit decision).
    """
    node = by_id.get(_RATIFIED_SCOPE_NODE)
    if node is None:
        return []
    try:
        body = (root / node.path).read_text(encoding="utf-8")
    except OSError:
        return []
    spec = _first_yaml_block_with_key(body, "RATIFIED_SCOPE")
    if not isinstance(spec, dict) or not isinstance(spec.get("cases"), int):
        # fail LOUD: a missing/broken block means the check silently stops guarding
        return [Finding(SEVERITY_WARN, str(node.path),
                        "RATIFIED_SCOPE block missing or unparseable — the precedent-library "
                        "scope check cannot run, so it is NOT passing, it is unverified")]
    ratified = spec["cases"]
    actual = sum(1 for n in nodes
                 if n.fm.get("status") == "active"
                 and _CASE_TITLE_RE.match(str(n.fm.get("title") or "")))
    # `re_ratify_at` (2026-09-08) — the count at
    # which the NEXT ratification is due. Until then growth past the ratified figure is
    # expected and silent; at it, the warning fires and names both numbers. Absent, the
    # older rule holds: any growth past `cases` warns. It lives in the same block the
    # validator reads for the same reason `cases` does — a trigger this node kept in
    # prose ("re-ratify at 25 or on productisation") was reached on 2026-09-08 and
    # nothing but a person reading the body would have noticed.
    due = spec.get("re_ratify_at")
    if isinstance(due, int) and due > ratified:
        if actual < due:
            return []
        return [Finding(SEVERITY_WARN, str(node.path),
                        f"precedent library holds {actual} cases; re-ratification was due at "
                        f"{due} (ratified at {ratified} on {spec.get('ratified_on','?')}). "
                        f"The controls were argued against a scope — re-ratify explicitly at "
                        f"{actual} and set the next `re_ratify_at`, or reduce the library.")]
    if actual <= ratified:
        return []
    return [Finding(SEVERITY_WARN, str(node.path),
                    f"precedent library holds {actual} cases; the risk acceptance was ratified "
                    f"at {ratified} ({spec.get('ratified_on','?')}). The controls were argued "
                    f"against a scope — re-ratify explicitly at {actual} or reduce the library. "
                    f"Raising the number is a decision, not a formality.")]


def validate_corpus(root: Path):
    nodes, by_id, skipped, valid_types, file_findings = load_corpus(root)
    valid_projects = load_registry_projects(root)
    findings = list(file_findings)
    if not valid_types:
        findings.append(Finding(SEVERITY_ERROR, "schemas/type-registry.md",
                                "type registry missing or unparseable — corpus is broken"))
    if not valid_projects:
        findings.append(Finding(SEVERITY_ERROR, "schemas/type-registry.md",
                                "project registry (PROJECT_REGISTRY) missing or "
                                "unparseable — corpus is broken"))
    findings += run_checks(nodes, by_id, valid_types, load_folder_map(root), valid_projects)

    # COMPLETENESS layer — unfiled rulings in session bodies. WARNINGS only, and
    # deliberately so: this never fails the corpus (spec §6, audit path). Legacy
    # sessions are still reported here — they are the promotion backlog.
    try:
        from completeness import scan_corpus, scan_stray_rulings
    except ImportError:
        from librarian.completeness import scan_corpus, scan_stray_rulings
    for node_id, unfiled in scan_corpus(root, nodes).items():
        path = str(by_id[node_id].path) if node_id in by_id else node_id
        for u in unfiled:
            findings.append(Finding(SEVERITY_WARN, path,
                                    f"unfiled ruling under '{u.section}' (line {u.line}): {u.text}"))

    # A rule the author self-labelled, sitting outside any rulings section — invisible
    # to the section-scoped scan above. Warning only and never a write refusal: this is
    # a heuristic on where a marker sits, not the exact test the section scan applies.
    for node_id, stray in scan_stray_rulings(root, nodes).items():
        path = str(by_id[node_id].path) if node_id in by_id else node_id
        for u in stray:
            findings.append(Finding(SEVERITY_WARN, path,
                                    f"self-labelled ruling outside a rulings section "
                                    f"(line {u.line}): {u.text}"))

    # Dangling pointers written in PROSE. `relates_to` has always been checked; the body
    # never was — see scan_body_refs. Warning, with a per-node opt-out.
    findings += scan_body_refs(root, nodes, by_id)

    # A ratified RISK ACCEPTANCE whose scope can grow silently: a node accepting a risk
    # over a library of case notes, whose controls were each argued against a specific
    # case count. It drifted TWICE — accepted at 5–7,
    # found at 15, re-ratified at 15, and at 17 two days later — because nothing counted.
    # Frontmatter-only (titles), so it stays deterministic, instant and cheap per the deterministic-read-path decision.
    findings += scan_ratified_scope(root, nodes, by_id)

    # NOTE: record-store files now live in Google Drive and are pointed at by Drive FILE ID
    # (`kind: gdrive_file`, the file-pointer decision). A file ID survives being moved
    # between folders — verified 2026-07-28 — so reorganising cannot break a pointer, which
    # removes that failure class rather than checking for it. Whether a Drive file still EXISTS
    # is an API call, so it stays out of this deterministic read path (the read-path audit).

    return findings, nodes, skipped, valid_types


def main(argv: list[str]) -> int:
    root = Path(argv[1]).resolve() if len(argv) > 1 else Path(__file__).resolve().parent.parent
    findings, nodes, skipped, valid_types = validate_corpus(root)

    print(f"OKF validate — corpus root: {root}")
    print(f"  vocabulary: {sorted(valid_types) or '(registry not found!)'}")
    print(f"  nodes: {len(nodes)}   skipped (no frontmatter): {len(skipped)}")
    for s in skipped:
        print(f"    - skipped: {s}")

    errors = [f for f in findings if f.severity == SEVERITY_ERROR]
    warns = [f for f in findings if f.severity == SEVERITY_WARN]
    if findings:
        print("\nfindings:")
        for f in sorted(findings, key=lambda x: (x.severity, x.path)):
            print(f)
    print(f"\n{'FAIL' if errors else 'OK'} — {len(errors)} error(s), {len(warns)} warning(s)")
    return 1 if errors else 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
